def langevin(H):
    H = np.asarray(H, dtype=np.float64)
    result = np.zeros_like(H)

    xi = (m_sat * np.abs(H)) / (k_B * Temp)

    small_field_mask = xi < 1e-6
    large_field_mask = xi > 20
    medium_field_mask = ~(small_field_mask | large_field_mask)

    result[small_field_mask] = xi[small_field_mask] / 3
    result[large_field_mask] = 1 - 1/xi[large_field_mask]

    xi_medium = xi[medium_field_mask]
    exp_2x = np.exp(2 * xi_medium)
    coth_x = 1 + 2/(exp_2x - 1)
    result[medium_field_mask] = coth_x - 1/xi_medium

    result = np.sign(H) * result

    return m_sat * result

def selection_field_2d(x, y, Gx, Gy):
    Hx = Gx * x
    Hy = Gy * y
    return Hx, Hy

def excitation_field_2d(t, A, f):
    Hx = A * np.cos(2 * np.pi * f * t)
    Hy = A * np.cos(2 * np.pi * f * t)
    return Hx, Hy

def raster_trajectory(t, grid_x, grid_y, total_time):
    total_points = len(grid_x) * len(grid_y)
    points_per_second = total_points / total_time

    point_idx = int(t * points_per_second)

    if point_idx >= total_points:
        point_idx = total_points - 1

    i = point_idx % len(grid_x)
    j = point_idx // len(grid_x)

    if j >= len(grid_y):
        j = len(grid_y) - 1

    x_scan = grid_x[i]
    y_scan = grid_y[j]

    return x_scan, y_scan

def lissajous_trajectory(t, fx, fy, amplitude_x, amplitude_y):
    x_scan = amplitude_x * np.sin(2 * np.pi * fx * t) #
    y_scan = amplitude_y * np.sin(2 * np.pi * fy * t) #
    return x_scan, y_scan

def total_magnetic_field_2d(x, y, t_val, scan_type='raster'):
    if scan_type == 'raster':
        x_scan, y_scan = raster_trajectory(t_val, x[0,:], y[:,0], Time)
    elif scan_type == 'lissajous':
        x_scan, y_scan = lissajous_trajectory(t_val, f_x_ffp, f_y_ffp, Lx/2, Ly/2)
    else:
        x_scan, y_scan = 0, 0

    H_sel_x, H_sel_y = selection_field_2d(x - x_scan, y - y_scan, Gx, Gy)
    H_exc_x, H_exc_y = excitation_field_2d(t_val, A_E, f_E)

    H_total_x = H_sel_x + H_exc_x
    H_total_y = H_sel_y + H_exc_y

    H_amplitude = np.sqrt(H_total_x**2 + H_total_y**2)

    return H_amplitude, (x_scan, y_scan), (H_total_x, H_total_y)

def coil_sensitivity_2d(x, y):
    distance = np.sqrt(x**2 + y**2)
    return 1.0 / (1.0 + (distance / 5.0e-3)**2)

def system_function_2d(x_grid, y_grid, t_val, scan_type='lissajous'):
    H_current, (x_ffp, y_ffp), _ = total_magnetic_field_2d(x_grid, y_grid, t_val, scan_type)
    m_current = langevin(H_current)

    H_next, (x_ffp_next, y_ffp_next), _ = total_magnetic_field_2d(x_grid, y_grid, t_val + delta_t, scan_type)
    m_next = langevin(H_next)

    dm_dt = (m_next - m_current) / delta_t
    s_xy = coil_sensitivity_2d(x_grid, y_grid)

    a_xyt = -mu_0 * s_xy * dm_dt

    return a_xyt, (x_ffp, y_ffp)

def measured_signal_2d(c_2d, x_grid, y_grid, t_values, scan_type='lissajous'):
    u = np.zeros_like(t_values)
    ffp_trajectory = []

    x_1d = x_grid[0, :]
    y_1d = y_grid[:, 0]

    for i, t_val in enumerate(t_values):
        a_xyt, ffp_pos = system_function_2d(x_grid, y_grid, t_val, scan_type)
        ffp_trajectory.append(ffp_pos)

        integrand = a_xyt * c_2d

        integral_x = np.trapz(integrand, x_1d, axis=1)
        u[i] = np.trapz(integral_x, y_1d)

    return u, ffp_trajectory

def reconstruct_concentration(u_signal, A_matrix, alpha=0.01):
    signal_norm = np.linalg.norm(u_signal)
    if signal_norm > 0:
        u_signal_normalized = u_signal / signal_norm
    else:
        u_signal_normalized = u_signal.copy()

    col_norms = np.linalg.norm(A_matrix, axis=0)
    col_norms[col_norms == 0] = 1
    A_normalized = A_matrix / col_norms

    U, s, Vt = np.linalg.svd(A_normalized, full_matrices=False)
    s_filtered = s / (s**2 + alpha**2)
    c_recon_normalized = Vt.T @ (s_filtered * (U.T @ u_signal_normalized))
    c_recon = c_recon_normalized / col_norms

    c_recon = np.maximum(c_recon, 0)
    if np.max(c_recon) > 0:
        c_recon = c_recon / np.max(c_recon)

    return c_recon

