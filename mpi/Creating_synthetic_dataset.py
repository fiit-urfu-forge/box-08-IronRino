def calculate_ssim(img1, img2, window_size=7, k1=0.01, k2=0.03):
    """
    Вычисление SSIM (Structural Similarity Index) на чистом NumPy
    """
    # Нормализуем изображения
    img1_norm = (img1 - img1.min()) / (img1.max() - img1.min() + 1e-10)
    img2_norm = (img2 - img2.min()) / (img2.max() - img2.min() + 1e-10)

    L = 1.0  # Для нормализованных изображений
    C1 = (k1 * L) ** 2
    C2 = (k2 * L) ** 2

    pad = window_size // 2
    img1_pad = np.pad(img1_norm, pad, mode='reflect')
    img2_pad = np.pad(img2_norm, pad, mode='reflect')

    ssim_total = 0.0
    count = 0

    for i in range(pad, img1_pad.shape[0] - pad):
        for j in range(pad, img1_pad.shape[1] - pad):
            window1 = img1_pad[i-pad:i+pad+1, j-pad:j+pad+1]
            window2 = img2_pad[i-pad:i+pad+1, j-pad:j+pad+1]

            mu1 = np.mean(window1)
            mu2 = np.mean(window2)

            sigma1_sq = np.var(window1)
            sigma2_sq = np.var(window2)
            sigma12 = np.cov(window1.flatten(), window2.flatten())[0, 1]

            numerator = (2 * mu1 * mu2 + C1) * (2 * sigma12 + C2)
            denominator = (mu1**2 + mu2**2 + C1) * (sigma1_sq + sigma2_sq + C2)

            ssim_total += numerator / denominator
            count += 1

    return ssim_total / count if count > 0 else 0.0

def calculate_psnr(img1, img2):
    """
    Вычисление PSNR (Peak Signal-to-Noise Ratio)
    """
    mse = np.mean((img1 - img2) ** 2)
    if mse == 0:
        return float('inf')

    max_pixel = max(img1.max(), img2.max())
    psnr_value = 20 * math.log10(max_pixel / math.sqrt(mse))
    return psnr_value

def calculate_spatial_resolution(img):
    """
    Оценка пространственного разрешения через FWHM (Full Width at Half Maximum)
    для каждого круга отдельно
    """
    nx, ny = img.shape

    # Координаты центров в пикселях
    center1_x_px = int((CIRCLE_PARAMS['center1'][0] + 1) * (nx - 1) / 2)
    center1_y_px = int((CIRCLE_PARAMS['center1'][1] + 1) * (ny - 1) / 2)
    center2_x_px = int((CIRCLE_PARAMS['center2'][0] + 1) * (nx - 1) / 2)
    center2_y_px = int((CIRCLE_PARAMS['center2'][1] + 1) * (ny - 1) / 2)

    # Анализируем круги
    fwhm_values = []

    for center_y, center_x, circle_name in [
        (center1_y_px, center1_x_px, "Круг 1"),
        (center2_y_px, center2_x_px, "Круг 2")
    ]:
        if 0 <= center_y < nx and 0 <= center_x < ny:
            # Горизонтальный профиль через центр круга
            if center_y < nx:
                horizontal_slice = img[center_y, max(0, center_x-20):min(ny, center_x+20)]
                fwhm_h = calculate_fwhm(horizontal_slice)
                fwhm_values.append(fwhm_h)

            # Вертикальный профиль через центр круга
            if center_x < ny:
                vertical_slice = img[max(0, center_y-20):min(nx, center_y+20), center_x]
                fwhm_v = calculate_fwhm(vertical_slice)
                fwhm_values.append(fwhm_v)

    # Возвращаем среднее FWHM
    return np.mean(fwhm_values) if fwhm_values else 0

def calculate_fwhm(slice_data):
    """Вычисление FWHM из одномерного среза"""
    if len(slice_data) == 0:
        return 0

    # Находим максимальное значение
    max_val = np.max(slice_data)
    if max_val == 0:
        return len(slice_data)

    half_max = max_val / 2

    # Находим индексы, где значение превышает половину максимума
    above_half = slice_data > half_max

    if not np.any(above_half):
        return len(slice_data)

    indices = np.where(above_half)[0]

    # Находим первый и последний индекс
    first_idx = indices[0]
    last_idx = indices[-1]

    # Вычисляем FWHM
    fwhm = last_idx - first_idx

    # Корректируем, если FWHM слишком маленький или большой
    if fwhm < 1:
        fwhm = 1
    elif fwhm > len(slice_data):
        fwhm = len(slice_data)

    return fwhm

