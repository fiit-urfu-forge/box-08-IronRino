def create_2d_concentration(x_grid, y_grid):
    c = np.zeros_like(x_grid)

    mask_circle = (x_grid - 0.002)**2 + (y_grid + 0.002)**2 <= (0.003)**2
    c[mask_circle] = 1.0

    mask_rect = (x_grid >= -0.005) & (x_grid <= -0.002) & (y_grid >= -0.003) & (y_grid <= 0.003)
    c[mask_rect] = 0.8

    mask_triangle = (y_grid >= 0.003) & (y_grid <= 0.006) & (x_grid >= -0.002) & (x_grid <= 0.003) & (y_grid <= -1.5*x_grid + 0.008)
    c[mask_triangle] = 0.6

    return c

